#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "freertos/FreeRTOS.h"
#include "freertos/queue.h"
#include "gfx.h"
#include "net.h"
#include "usbdev.h"

// Contract between the system and the apps.
//
// An app is a static descriptor (app_desc_t) with a run() function that runs
// in a dedicated task. When run() returns the app has terminated and the
// system automatically releases all shared resources (USB profile, lent SD,
// the app's LED layer, network): an app does not have to remember to do it,
// although it may do it earlier on its own.
//
// To add an app: create a component in apps/, export its app_desc_t and add
// it to the table in main/app_list.c.

typedef enum {
    APP_REQ_SD = 1 << 0,   // SD mounted (FAT) on /sd
    APP_REQ_CARD = 1 << 1, // the card just needs to be present (even non-FAT)
    APP_REQ_NET = 1 << 2,  // will use the network (WiFi)
    APP_REQ_BLE = 1 << 3,  // reserved: BLE not implemented yet
} app_req_t;

typedef enum {
    APP_EV_CLICK,
    APP_EV_DOUBLE,
    APP_EV_LONG,
    APP_EV_EXIT,   // the user held the button for 3 s: terminate as soon as possible
    APP_EV_USB,    // arg = usbdev_event_t
    APP_EV_NET,    // arg = network event (see net.h)
    APP_EV_TICK,   // generated by the app itself with app_post (timers, tasks)
    APP_EV_USER,   // free for the app's use
    // Answer to the open dialog (app_menu*, app_confirm*, app_message) given
    // from outside, for example from a web page: arg = item index, or 0/1 for
    // no/yes. The dialog treats it like a choice made with the button, so the
    // first answer wins. Outside a dialog it is discarded.
    APP_EV_ANSWER,
} app_ev_type_t;

typedef struct {
    app_ev_type_t type;
    int32_t arg;
} app_event_t;

typedef struct app_desc app_desc_t;

typedef struct {
    const app_desc_t *app;
    const char *arg;       // launch argument (e.g. the autorun payload), may be NULL
    QueueHandle_t queue;
    volatile bool exit_requested;
    volatile bool exit_lost; // the EXIT did not fit in the full queue: app_next_event delivers it
} app_ctx_t;

struct app_desc {
    const char *id;                 // short identifier, used in config.lua (autorun)
    const char *name;               // name shown in the launcher
    const gfx_icon_t *icon;         // 12x12 pixel art icon (drawn at 2x)
    uint32_t accent;                // accent color: UI and LED
    uint32_t requires;              // mask of app_req_t
    usb_profile_t usb;              // USB profile active while the app runs (mask of USB_F_*)
    uint32_t stack;                 // stack of the app's task in bytes
    void (*run)(app_ctx_t *ctx);
    // Optional: info line below the name in the launcher.
    void (*subtitle)(char *buf, size_t len);
};

// Waits for the next event. false if the timeout expires (portMAX_DELAY to
// wait forever). An APP_EV_EXIT is always delivered, even if the queue was
// full when it was requested.
//
// Delivering the event is not enough to make an app exit: the app has to go
// back to waiting for one. If it does not (long computation, blocking call),
// after 3 s the system offers a reboot with a second hold (see appmgr.c).
bool app_next_event(app_ctx_t *ctx, app_event_t *ev, uint32_t timeout_ms);
bool app_should_exit(app_ctx_t *ctx);
// Queues an event (useful from the app's timers or secondary tasks). With
// APP_EV_EXIT it also sets exit_requested: it is the way to request exit
// from inside the app (e.g. a timeout).
void app_post(app_ctx_t *ctx, app_ev_type_t type, int32_t arg);
// Cancels an exit request already received (e.g. the hold only interrupted
// a script, or the user answered "No" to "Exit?") and discards the EXITs
// still queued, so the next dialog does not close by itself.
void app_cancel_exit(app_ctx_t *ctx);

// --- Ready-to-use blocking dialogs ---

// Dialogs consume only gestures: the other events that arrive while they
// are open (USB, network, TICK, USER) go back to the queue when they close.
//
// List menu: click = down, double = up, long = choose.
// Returns the chosen index or -1 if the app must exit.
int app_menu(app_ctx_t *ctx, const char *title, const char *const *items, int count, int selected);
// Like app_menu, with a text column to the right of each row (rights may be
// NULL, and each element may be NULL).
int app_menu_ex(app_ctx_t *ctx, const char *title, const char *const *items, const char *const *rights, int count,
                int selected);
// Like app_menu_ex; if there is no gesture within timeout_ms (0 = never) it
// returns `selected`. The countdown appears in the title, a click or a
// double click stops it.
int app_menu_timeout(app_ctx_t *ctx, const char *title, const char *const *items, const char *const *rights, int count,
                     int selected, uint32_t timeout_ms);
// Yes/no question: click toggles, long confirms. false also on exit.
bool app_confirm(app_ctx_t *ctx, const char *title, const char *text, bool default_yes);
// Like app_confirm; if there is no gesture within timeout_ms (0 = never) it returns
// default_yes. A click disables the timeout.
bool app_confirm_timeout(app_ctx_t *ctx, const char *title, const char *text, bool default_yes, uint32_t timeout_ms);
// Message: waits for click or long. A text that does not fit scrolls by itself.
void app_message(app_ctx_t *ctx, const char *title, const char *text, uint32_t color);

// --- USB ---

// Changes the USB profile while the app runs (e.g. to attach the disk
// mid-script) and hands the SD to the host or takes it back according to
// USB_F_DISK_RW/RO. When the app exits the manager returns to the NONE
// profile anyway. If the new profile fails TinyUSB stays off and the SD goes
// back to the firmware.
esp_err_t app_usb_apply(usb_profile_t profile);

// The app changed config.lua (e.g. the web file browser): it must be
// reloaded. Not immediately, because config_load frees the config_str
// strings the apps are using: the system does it when the app exits.
void app_config_changed(void);

// --- Network ---

// net_acquire with the network choice left to the user: if several known
// networks are visible a menu appears (with RSSI) and, with no answer within
// a few seconds, the strongest one is used. Returns ESP_ERR_NOT_FINISHED if
// the user exits during the choice or while waiting for the connection.
esp_err_t app_net_acquire(app_ctx_t *ctx, net_mode_t mode, uint32_t timeout_ms);
